#!/usr/bin/env bash
# ============================================================================
# net-up.sh — isolated STB subnet + DNS spoof for the GenieACS trick.
#
#   STB --- cable --- [spare ethernet NIC] PC
#   PC = 10.10.10.1/24 (manual profile "stb-isolated", no gateway, never-default)
#   dnsmasq on THAT interface only: DHCP 10.10.10.50-99 + acs.oss.jio.com -> 10.10.10.1
#
# Everything created here is removed by ./net-down.sh.
# Nothing touches your Wi-Fi, your default route, or your router.
#
#   sudo ./net-up.sh              # auto-pick a free ethernet NIC
#   sudo ./net-up.sh enp0s31f6    # explicit NIC
# ============================================================================
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
RUN="$HERE/run"
CON=stb-isolated
HOST_IP=10.10.10.1
PREFIX=24
NET=10.10.10.0/24

if [[ $EUID -ne 0 ]]; then echo "run as root: sudo $0" >&2; exit 1; fi
command -v dnsmasq >/dev/null || { echo "dnsmasq missing: sudo pacman -S dnsmasq" >&2; exit 1; }
command -v nmcli   >/dev/null || { echo "NetworkManager/nmcli missing" >&2; exit 1; }

# ---- pick interface -------------------------------------------------------
IFACE="${1:-${STB_IFACE:-}}"
if [[ -z "$IFACE" ]]; then
  # first physical ethernet NIC (skip docker0/br-*/veth)
  IFACE="$(nmcli -t -f DEVICE,TYPE device status \
    | awk -F: '$2=="ethernet" && $1 !~ /^(docker|br-|veth|virbr)/ {print $1; exit}')"
fi
[[ -n "$IFACE" ]] || { echo "no ethernet NIC found — pass one: sudo $0 <iface>" >&2; exit 1; }
ip link show "$IFACE" >/dev/null 2>&1 || { echo "interface '$IFACE' does not exist" >&2; exit 1; }

mkdir -p "$RUN"

# ---- 1. static IP profile (no gateway, no DNS, never default route) ------
if ! nmcli -t -f NAME connection show | grep -qx "$CON"; then
  nmcli connection add type ethernet ifname "$IFACE" con-name "$CON" \
    ipv4.method manual \
    ipv4.addresses "$HOST_IP/$PREFIX" \
    ipv4.gateway "" \
    ipv4.dns "" \
    ipv4.never-default yes \
    ipv4.route-metric 1000 \
    ipv6.method disabled >/dev/null
fi
# re-apply against the current NIC name if the profile already existed
nmcli connection modify "$CON" connection.interface-name "$IFACE"
nmcli connection up "$CON" >/dev/null 2>&1 || echo "  ! link not up yet ($IFACE has no carrier until the STB is plugged in)"
ip addr show "$IFACE" | grep -q "$HOST_IP/$PREFIX" || ip addr add "$HOST_IP/$PREFIX" dev "$IFACE" 2>/dev/null || true

# ---- 2. dnsmasq: DHCP + spoofed A record, on this interface only ---------
cat > "$RUN/dnsmasq.conf" <<EOF
# generated by net-up.sh — safe to delete
interface=$IFACE
bind-interfaces
port=53
# never forward anything upstream: the STB must not resolve or reach the internet
no-resolv
no-hosts
domain-needed
bogus-priv
local-service
log-dhcp
log-facility=$RUN/dnsmasq.log
# --- the redirect the exploit needs ---
address=/acs.oss.jio.com/$HOST_IP
# --- DHCP for the STB (its only way onto this subnet) ---
dhcp-range=10.10.10.50,10.10.10.99,255.255.255.0,2h
dhcp-option=3,$HOST_IP
dhcp-option=6,$HOST_IP
dhcp-authoritative
EOF

if [[ -f "$RUN/dnsmasq.pid" ]] && kill -0 "$(cat "$RUN/dnsmasq.pid")" 2>/dev/null; then
  kill "$(cat "$RUN/dnsmasq.pid")" 2>/dev/null || true
  sleep 1
fi
dnsmasq --conf-file="$RUN/dnsmasq.conf" --pid-file="$RUN/dnsmasq.pid"

# ---- 3. sanity report ----------------------------------------------------
echo
echo "  interface : $IFACE"
echo "  PC address: $HOST_IP/$PREFIX  (profile '$CON', no gateway)"
echo "  DHCP      : 10.10.10.50-99"
echo "  DNS       : acs.oss.jio.com -> $HOST_IP   (dnsmasq pid $(cat "$RUN/dnsmasq.pid" 2>/dev/null))"
[[ "$(sysctl -n net.ipv4.ip_forward 2>/dev/null || echo 0)" == "0" ]] \
  && echo "  forwarding: off  (STB cannot reach the internet) " \
  || echo "  ! net.ipv4.ip_forward=1 — the STB could route out. Set it to 0."
echo
echo "  Next: sudo ./acs-up.sh   then plug the STB in and power it on."
